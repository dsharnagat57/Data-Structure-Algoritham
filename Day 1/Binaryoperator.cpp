#include <iostream>
using namespace std;

int main()
{
// Binary operator (works on two operands)
    // 1. Addition operator (+)
            
    int x = 10, y = 5;
    cout << x + y << endl;  

    // 2. Subtraction operator (-)

    cout << x - y << endl;

    // 3. Multiplication operator (*)

    cout << x * y << endl;

    // 4. Division operator (/)

    cout << x / y << endl;

    // 5. Modulus operator (%)

    cout << x % y << endl;
    return 0;
}