#include <iostream>
using namespace std;

int main()
{
   
// Relational operators (used to compare two values and return a boolean result)

    int a=20, b=10;
    cout << (a==b) << endl;
    cout << (a>b) << endl;
    cout << (a<b) << endl;
    cout << (a!=b) << endl;
    cout << (a>=b) << endl;
    cout << (a<=b) << endl;
    return 0;
}